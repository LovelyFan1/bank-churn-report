# ── 豁免：问句里若同时出现这些，说明用户其实在问**能答**的东西 ──
# 只拦「纯」不支持类问题。否则「明年趋势如何，另外现在高危有多少人」
# 会被整句拦掉，而其中一半是可答的。
#
# ⚠ 本表的设计约束（踩过坑，务必遵守）：**只放"话题+可答意图"的组合短语，
#   不放光秃秃的名词**。
#   实测事故：曾在此表放入裸名词「负责人」，导致
#       「哪个负责人的挽留效果最好」被豁免 → 漏拦 → LLM 会去编业绩排名。
#   原因：裸名词几乎什么都豁免（"负责人"会出现在各种句子里），
#   于是规则永远不触发。
#   正确做法是放「可答的问法」，如"哪个负责人在手多少单"——
#   它含"负责人"但意图是查工单数，可答。
_ANSWERABLE_HINTS = [
    "高危", "高风险", "极高", "中等风险", "低风险",
    "余额", "价值层", "期望价值", "盈亏平衡", "值得",
    "阈值", "决策线", "分级", "成本比", "精准率", "召回",
    "名单", "多少人", "多少个", "几个", "哪些客户",
    "工单", "建单",
    # 负责人维度：只有落到**具体可查的量**时才豁免
    "在手多少", "手上多少", "工单数", "处理了多少",
    "客户 C", "C0", "C1", "C2",  # 具体客户编号
]

_NUMERIC_CLIENT_ID = re.compile(r"\bC\d{4,}\b", re.IGNORECASE)


@dataclass
class GuardHit:
    key: str
    reason: str
    instead: str

    def to_message(self) -> str:
        return f"这个问题我答不了：{self.reason}\n\n{self.instead}"


def check(question: str) -> GuardHit | None:
    """检查问句是否命中拒答规则。命中返回 GuardHit，否则 None。

    ⚠ 纯函数、无副作用、不调 LLM —— 因此可单元测试，且行为完全可预测。
      这是本层存在的意义：拒答必须是**可复现**的，不能每次表现不同。
    """
    if not question or not question.strip():
        return None

    q = question.strip()

    # 豁免一：问句里含具体客户编号 → 一定是想问这个客户，不拦
    if _NUMERIC_CLIENT_ID.search(q):
        return None

    hit = None
    for rule in _RULES:
        if any(kw in q for kw in rule["must"]):
            hit = rule
            break

    if hit is None:
        return None

    # 豁免二：问句里含"可答主题"的提示词 → 整句交给 LLM 处理
    # 例：「明年趋势怎样，另外现在高危有多少人」
    if any(h in q for h in _ANSWERABLE_HINTS):
        return None

    return GuardHit(key=hit["key"], reason=hit["why"], instead=hit["instead"])


def known_topics() -> list[dict]:
    """对外暴露"答不了的主题清单"—— 供前端展示与答辩说明。

    主动告诉用户"我不能回答什么"，比等被问到时支吾更有价值：
    它把系统的**边界**变成了产品能力。
    """
    return [{"key": r["key"], "why": r["why"], "instead": r["instead"]}
            for r in _RULES]


# ── 写意图识别（确定性）──────────────────────────────────
#
# ⚠ 为什么需要这一层（实测缺陷，diag108）：
#   问「帮我给 C034525 建个挽留工单，负责人写张思远」时，LLM **没有**
#   调用 propose_create_work_order，而是先调 get_customer_risk，
#   然后**在回答正文里自己写了一段"## 工单信息（待确认）"** ——
#   用文字模拟了待确认动作。
#
#   后果：数据库没被写（安全），但**功能完全失效** ——
#   前端拿不到 pending_action，用户看不到确认按钮，
#   而回答却读起来像"已经准备好了"。这比直接失败更糟：
#   用户会以为点了就能建，实际什么都没有。
#
#   这是与 Guard 同一类问题：**靠提示词要求模型调工具是不可靠的**。
#   故此处用确定性规则识别写意图，在图上**强制**该工具被调用
#   （通过 tool_choice 参数，见 graph.node_agent）。
#
# 设计取舍：识别到写意图但**没有客户编号**时，不强制（无法构造参数），
#   交给 LLM 正常追问 —— 强行调用只会得到一个报错的工具结果。

_WRITE_KEYWORDS = [
    "建单", "建个单", "建工单", "创建工单", "创建工作单", "开个工单",
    "派给", "派单", "分配给", "指派给", "安排给",
    "帮我建", "给我建", "给.*建.*单",
    "生成工单", "下个工单", "开单",
    # ── 取消/删除/改单（实测缺口 diag116）──────────────────
    # 用户问「帮我取消已建单待处理状态客户」时，Agent **没有任何工具**
    # 能完成这件事，却凭记忆答「没有已建单待处理状态的客户」。
    # 补上这两类关键词后，写意图会被识别并走强制提议流程。
    "取消工单", "取消已建单", "取消建单", "取消这个单", "取消那张单",
    "删除工单", "删掉工单", "删掉这个单", "删了这单",
    "标记为已完成", "标记完成", "标为完成", "结单",
    "改状态", "修改工单", "改成处理中", "改成已流失",
]

# 明确的"不要执行"信号 —— 用于排除询问性问法
_INQUIRY_KEYWORDS = ["能不能", "可以吗", "该不该", "要不要", "是否应该", "为什么"]

_CID_RE = re.compile(r"\bC\d{4,}\b", re.IGNORECASE)


def detect_write_intent(question: str) -> tuple[bool, str | None, str | None]:
    """识别"要求建单"的写意图。

    返回 (是否写意图, 客户编号, 负责人姓名或 None)。

    ⚠ 询问性问法不算写意图：
      「C034525 要不要建单」是**咨询**，应让模型回答该不该建；
      「给 C034525 建单」是**指令**，必须走待确认流程。
      区分靠 _INQUIRY_KEYWORDS。

    ⚠ 为什么要在这里抽负责人（而非交给 LLM）：当识别到写意图时，
      图会**强制**调用 propose_create_work_order（tool_choice），
      此时模型没有机会自行抽参 —— 参数由它按上下文填，可能漏掉
      "负责人写张思远"这样的用户明确要求。故此处在规则层一并抽出，
      作为兜底传给工具（见 graph.node_tools 的合并逻辑）。
    """
    if not question:
        return False, None, None
    q = question.strip()

    # 询问性问法 → 不是写指令
    if any(k in q for k in _INQUIRY_KEYWORDS):
        return False, None, None

    hit = False
    for kw in _WRITE_KEYWORDS:
        if re.search(kw, q):
            hit = True
            break
    if not hit:
        return False, None, None

    m = _CID_RE.search(q)
    cid = m.group(0).upper() if m else None
    return True, cid, _extract_assignee(q)


# 负责人抽取：匹配「负责人(是|写|叫|填)?X」「派给X」「指派给X」「分配给X」
# X 为 2~4 个中文字 或 ASCII 单词。已知系统内负责人：
#   111 / 张思远 / 李铭 / 王晓芸 / 赵敏 / 陈立群
_ASSIGNEE_PATTERNS = [
    re.compile(r"负责人(?:是|写|叫|填|为|：|:)?\s*([\u4e00-\u9fa5A-Za-z0-9]{1,10})"),
    re.compile(r"(?:派给|指派给|分配给|安排给|交给)\s*([\u4e00-\u9fa5A-Za-z0-9]{1,10})"),
]

# 这些词出现在负责人位置说明抽取失败（是动词/助词而非人名）
_ASSIGNEE_STOPWORDS = {"他", "她", "它", "我", "你", "客户", "这个人", "该客户",
                       "一下", "吧", "了", "的", "处理", "跟进"}


def _extract_assignee(q: str) -> str | None:
    for pat in _ASSIGNEE_PATTERNS:
        m = pat.search(q)
        if not m:
            continue
        name = m.group(1).strip()
        if name and name not in _ASSIGNEE_STOPWORDS:
            return name
    return None
