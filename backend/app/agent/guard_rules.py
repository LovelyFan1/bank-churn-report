"""Guard —— 拒答硬拦截（确定性规则，不依赖 LLM）。

**为什么必须有这一层（实测依据）**

`diag103` 实测：把工具定义交给 DeepSeek 后问「哪个策略挽留效果最好？」，
它**没有拒答**，而是调用了 `get_model_thresholds`（阈值工具）—— 一个与
策略效果毫无关系的工具。而问「明年的流失趋势」时它正确拒答了。

即：**LLM 的拒答能力不稳定**，同一类"数据不支持"的问题，有时拒、有时乱调。
靠提示词写"答不了就别答"是祈祷，不是工程。

因此本层用**确定性规则**在调用 LLM 之前拦截。规则来自本系统实测的三条
数据硬约束（见 DEFECT-REPORT 12.4 / 12.6 / 12.10）：

  1. 真实挽留成功率 —— 60 条工单的 result 来自 seed_work_orders.py 的
     硬编码常量表 STATUS_PLAN，不是任何真实回访结果
  2. 任何年化 / 趋势 / 预测 —— 客户表**零个时间语义字段**
  3. 哪个策略 / 渠道更有效 —— retention-summary 的 by_strategy 只有 1 行

**设计取舍：宁可多拦，不可漏拦**

误拦一个有答案的问题（用户看到"这个我答不了"）比漏拦导致 LLM 编造
（用户看到假数字并据此决策）后果轻得多。故规则表取**保守**策略：
主题词 + 疑问词组合命中即拦。用户若确实想要相关数据，追问明细即可。

⚠ 但**问句里同时含"不支持的主题"与"支持的主题"时不拦**，交给 LLM ——
   例如「明年的流失趋势如何，另外现在高危有多少人」前半句答不了、
   后半句能答。这里只拦**纯**不支持类问题，故用"是否含可答关键词"做豁免。
"""

